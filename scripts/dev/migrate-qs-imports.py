#!/usr/bin/env python3
"""Make the shell tree loadable by file: URLs, so that Qt's QML disk cache works (ADR-0056, draft).

Quickshell loads a config through `qs:@/qs/...` URLs, and Qt's disk cache refuses them ("File has to be a local file"): every
.qml and .js file is compiled from source at every start (about 48 % of the start's CPU, R7-REL-01). A tree whose documents are
all reached through file: URLs is cached. This script rewrites a COPY (or, with --in-place, the tree itself):

  * every `import qs.<a>.<b>` becomes the relative directory import `import "<relative path to shell/<a>/<b>>"` (the
    directory's qmldir keeps its singleton entries, so a singleton is one instance: every document of the process has one
    file: URL, and nothing in the process is reached through qs:);
  * the root file shell.qml (ROOTS, --roots; security.qml is kept as it is until its security review) becomes a stub,
    `shell.qml`, that holds `settings.watchFiles: false`, the root's `//@ pragma` lines and a LazyLoader of `shell-core.qml` by
    file: URL from Quickshell.shellDir; the former root, with ShellRoot turned into Scope, is `shell-core.qml`. A core that
    fails to load ends the process after 10 s by SIGABRT with an error line (a failure for systemd, never status 0).

It is deterministic (sorted walk, no timestamps) and idempotent: a migrated tree is left as it is. The source tree of the
repository stays in the `import qs.*` form (the layering checkers read it); the intended use is at packaging time:

  scripts/dev/migrate-qs-imports.py --out "$pkgdir/usr/share/grassfield/shell"      (copy of shell/, migrated)
  scripts/dev/migrate-qs-imports.py --in-place TREE                                 (a scratch copy, tests)
  scripts/dev/migrate-qs-imports.py --check TREE                                    (exit 1 when TREE still has qs imports)

New files need no rule: write `import qs.<module>` as before.
"""
import argparse
import os
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ROOTS = ("shell.qml",)  # the UI process only; security.qml stays as it is until its security review (ADR-0056)
MARK = "Generated by scripts/dev/migrate-qs-imports.py"
IMPORT = re.compile(r"^(?P<ind>\s*)import\s+qs\s*\.\s*(?P<mod>[A-Za-z_]\w*(?:\s*\.\s*[A-Za-z_]\w*)*)(?P<rest>.*)$")
ANY_QS_IMPORT = re.compile(r"\bimport\s+qs\b")
WATCH = re.compile(r"^\s*settings\.watchFiles:\s*false\s*(//.*)?$")


class Fail(Exception):
    pass


def code_lines(text):
    """(index, line, in_code): in_code is False for lines inside a block comment or starting a line comment."""
    block = False
    for i, line in enumerate(text.split("\n")):
        stripped = line.strip()
        if block:
            if "*/" in line:
                block = False
            yield i, line, False
            continue
        if stripped.startswith("//"):
            yield i, line, False
            continue
        if stripped.startswith("/*") and "*/" not in stripped:
            block = True
            yield i, line, False
            continue
        yield i, line, True


def rewrite_imports(path, tree, text):
    """The text with every `import qs.x.y` made relative; raises Fail on an import it cannot resolve."""
    out = text.split("\n")
    here = path.parent
    for i, line, code in code_lines(text):
        if not code:
            continue
        m = IMPORT.match(line)
        if not m:
            if ANY_QS_IMPORT.search(line.split("//")[0]):
                raise Fail(f"{path.relative_to(tree)}:{i + 1}: an import of qs this script cannot read: {line.strip()}")
            continue
        parts = [p.strip() for p in m.group("mod").split(".")]
        target = tree.joinpath(*parts)
        if not (target / "qmldir").is_file():
            raise Fail(f"{path.relative_to(tree)}:{i + 1}: qs.{'.'.join(parts)} is not a module (no {target.relative_to(tree)}/qmldir)")
        rel = os.path.relpath(target, here).replace(os.sep, "/")
        out[i] = f'{m.group("ind")}import "{rel}"{m.group("rest")}'
    return "\n".join(out)


def split_root(path, text):
    """(stub text, core text) for a root file."""
    if MARK in text:
        return None
    lines = text.split("\n")
    pragmas = [l for l in lines if l.startswith("//@")]
    core = []
    seen_root = seen_watch = False
    for l in lines:
        if l.startswith("//@"):
            continue  # the pragmas belong to the stub, the file Quickshell reads them from
        if not seen_root and re.match(r"^ShellRoot\s*\{", l):
            l = re.sub(r"^ShellRoot", "Scope", l)
            seen_root = True
        elif WATCH.match(l):
            seen_watch = True
            continue
        core.append(l)
    if not seen_root:
        raise Fail(f"{path.name}: no top-level `ShellRoot {{`")
    if not seen_watch:
        raise Fail(f"{path.name}: no `settings.watchFiles: false` (a reload is a security event: R12, the stub must carry it from a root that has it)")
    core_name = path.stem + "-core.qml"
    stub = "\n".join(pragmas + [f"""// {MARK}: the stub root of {path.name}. The tree below is loaded by file: URLs (ADR-0056),
// so that Qt's QML disk cache serves it; the former root is {core_name}.
import QtQml
import Quickshell
import Quickshell.Io

ShellRoot {{
    id: stub

    // Never reload on a file change (R12), as the former root did.
    settings.watchFiles: false

    LazyLoader {{
        id: core
        active: true
        source: "file://" + Quickshell.shellDir + "/{core_name}"
    }}

    // A core that did not load leaves a root that hosts nothing, and the process must END AS A FAILURE, never with status 0:
    // the unit's Restart= and OnFailure= (the failure counter, safe mode: ADR-0041 step 1a) act on failures only. Quickshell has
    // no exit with a code from QML (Qt.quit() is status 0, Qt.exit(n) has no receiver), so the stub signals its own process:
    // SIGABRT ends it by a signal (a failure for systemd; with QS_DISABLE_CRASH_HANDLER=1 and LimitCORE=0 no report is run and
    // no core file is written; the journal records the crash). The check waits for the event loop (LazyLoader.item is set
    // after this root's Component.onCompleted) and for 10 s.
    Process {{
        id: die
        command: ["sh", "-c", "kill -ABRT $PPID"]
    }}
    Timer {{
        interval: 10000
        running: true
        onTriggered: {{
            if (core.item === null) {{
                console.error("{path.name}: {core_name} did not load");
                die.running = true;
            }}
        }}
    }}
}}
"""])
    return stub, "\n".join(core)


def top_level(tree):
    """The .qml files at the top of the tree that are roots (not a generated core)."""
    return sorted(p for p in tree.glob("*.qml") if not p.name.endswith("-core.qml"))


def migrate(tree, roots_to_split=ROOTS):
    """Rewrite the imports of every file; split the roots named in roots_to_split; leave the other top-level roots as they are
    (security.qml, until the security review of ADR-0056 is done: the security process keeps loading it through qs:)."""
    changed = []
    roots = [p for p in top_level(tree) if p.name in roots_to_split]
    kept = [p for p in top_level(tree) if p.name not in roots_to_split]
    for path in sorted(tree.rglob("*.qml")):
        if path in kept:
            continue
        if path in roots and MARK in path.read_text(encoding="utf-8"):
            continue
        text = path.read_text(encoding="utf-8")
        new = rewrite_imports(path, tree, text)
        if path in roots:
            parts = split_root(path, new)
            if parts is not None:
                stub, core = parts
                (path.parent / (path.stem + "-core.qml")).write_text(core, encoding="utf-8")
                new = stub
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed.append(path)
    for path in sorted(tree.rglob("*.js")):
        text = path.read_text(encoding="utf-8")
        for i, line in enumerate(text.split("\n")):
            if re.match(r"^\s*\.import\s+qs\b", line):
                raise Fail(f"{path.relative_to(tree)}:{i + 1}: a JS `.import qs` (none exists at this commit)")
    return changed


def pending(tree, roots_to_split=ROOTS):
    left = []
    kept = [p for p in top_level(tree) if p.name not in roots_to_split]
    for path in sorted(tree.rglob("*.qml")):
        if path in kept:
            continue
        text = path.read_text(encoding="utf-8")
        if any(code and ANY_QS_IMPORT.search(l.split("//")[0]) for _, l, code in code_lines(text)):
            left.append(path)
    return left


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("tree", nargs="?", help="a tree to migrate in place (with --in-place) or to check (--check)")
    ap.add_argument("--out", help="copy shell/ (or --src) to this directory and migrate the copy")
    ap.add_argument("--src", default=str(ROOT / "shell"), help="the source tree for --out (default: shell/)")
    ap.add_argument("--in-place", action="store_true", help="migrate TREE itself")
    ap.add_argument("--check", action="store_true", help="exit 1 when TREE has an `import qs.*` left")
    ap.add_argument("--dry-run", action="store_true", help="migrate a temporary copy of --src and exit 1 when that fails (CI: every new file migrates)")
    ap.add_argument("--roots", default=",".join(ROOTS), help="the top-level roots to turn into stubs (default: shell.qml, the UI)")
    a = ap.parse_args()
    roots = tuple(r for r in a.roots.split(",") if r)
    try:
        if a.dry_run:
            import tempfile
            with tempfile.TemporaryDirectory() as t:
                tree = pathlib.Path(t) / "shell"
                shutil.copytree(a.src, tree)
                migrate(tree, roots)
                again = migrate(tree, roots)
                left = pending(tree, roots)
                if left or again:
                    raise Fail("not migrated or not idempotent: " + ", ".join(str(p.relative_to(tree)) for p in left + again))
            print("migrate-qs-imports: the whole tree migrates")
            return 0
        if a.check:
            left = pending(pathlib.Path(a.tree), roots)
            for p in left:
                print(f"migrate-qs-imports: {p} still imports qs.*")
            return 1 if left else 0
        if a.out:
            out = pathlib.Path(a.out)
            if out.exists():
                shutil.rmtree(out)
            shutil.copytree(a.src, out)
            tree = out
        elif a.in_place and a.tree:
            tree = pathlib.Path(a.tree)
        else:
            ap.error("give --out DIR, or --in-place TREE, or --check TREE")
        changed = migrate(tree, roots)
        left = pending(tree, roots)
        if left:
            raise Fail("imports of qs left in " + ", ".join(str(p.relative_to(tree)) for p in left))
        print(f"migrate-qs-imports: {len(changed)} file(s) changed in {tree}")
        return 0
    except Fail as e:
        print(f"migrate-qs-imports: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
