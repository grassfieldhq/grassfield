#!/usr/bin/env bash
# Interim build of grassfield-compositor without CMake/Ninja (not installed yet; see README.md).
# Writes the same outputs as the CMake build: build/grassfield-compositor.so, build/grassfield-compositor-tests
# and build/compile_commands.json (for clang-tidy, gate Q1).
# Usage: compositor/build-direct.sh [plugin|tests|tests-asan|compdb|all|tidy]   (default: all = plugin + tests + compdb)
#   tests-asan: the unit tests (ParserFuzzTest included) built again with -fsanitize=address,undefined into
#   build/grassfield-compositor-tests-asan (ADR-0041 step 5); `tests` and `tests-asan` need gtest only, not Hyprland's headers.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p build
what=${1:-all}

core_srcs=(src/core/Protocol.cpp src/core/TitlebarLayout.cpp src/core/PointerGesture.cpp src/core/Minimize.cpp src/core/Appmenu.cpp
  src/core/EventThrottle.cpp src/core/Overview.cpp src/core/DesktopFocus.cpp src/core/Json.cpp src/core/Stages.cpp src/core/CursorRefresh.cpp
  src/core/DeferredFocus.cpp src/core/OverviewFocus.cpp src/core/Genie.cpp src/core/Tiling.cpp src/core/LayerPointer.cpp src/core/ClientChrome.cpp src/core/FrameLog.cpp src/core/Quiet.cpp
  src/core/Notices.cpp src/core/RunMode.cpp src/core/TopClamp.cpp src/core/WindowRim.cpp)
glue_srcs=(src/main.cpp src/Titlebar.cpp src/Ipc.cpp src/Minimize.cpp src/AppmenuServer.cpp src/Overview.cpp src/DesktopFocus.cpp src/Surfaces.cpp src/WindowTransform.cpp src/Stages.cpp src/CursorRefresh.cpp src/DeferredFocus.cpp src/OverviewFocus.cpp src/GenieDraw.cpp src/Tiling.cpp src/LayerPointer.cpp src/ClientChrome.cpp src/FrameProbe.cpp src/TopClamp.cpp src/WindowRim.cpp)
plugin_srcs=("${glue_srcs[@]}" "${core_srcs[@]}")
test_srcs=(tests/ProtocolTest.cpp tests/TitlebarLayoutTest.cpp tests/PointerGestureTest.cpp tests/MinimizeTest.cpp tests/AppmenuTest.cpp
  tests/EventThrottleTest.cpp tests/OverviewTest.cpp tests/DesktopFocusTest.cpp tests/StagesTest.cpp tests/CursorRefreshTest.cpp
  tests/DeferredFocusTest.cpp tests/OverviewFocusTest.cpp tests/GenieTest.cpp tests/TilingTest.cpp tests/LayerPointerTest.cpp tests/ClientChromeTest.cpp tests/FrameLogTest.cpp tests/QuietTest.cpp
  tests/NoticesTest.cpp tests/RunModeTest.cpp tests/TopClampTest.cpp tests/WindowRimTest.cpp tests/ParserFuzzTest.cpp)

# Every source file is in one of the lists above, which also feed the compile database and so clang-tidy
# (scripts/dev/tidy.sh): a file left out was neither built here nor linted (core/Notices.cpp and its test were, until
# the run-mode slice M7). Keep them in step with CMakeLists.txt. Every C or C++ source under src/ and tests/ counts, at
# any depth and with any of the usual extensions (review of e0a3734: a new subdirectory or a .cc file passed).
unlisted=()
while IFS= read -r -d '' f; do
  [[ " ${glue_srcs[*]} ${core_srcs[*]} ${test_srcs[*]} " == *" $f "* ]] || unlisted+=("$f")
done < <(find src tests -type f \( -name '*.cpp' -o -name '*.cc' -o -name '*.cxx' -o -name '*.c++' -o -name '*.c' \) -print0 | sort -z)
if ((${#unlisted[@]})); then
  echo "build-direct: not in core_srcs, glue_srcs or test_srcs (and so not built here nor linted): ${unlisted[*]}" >&2
  exit 1
fi

# Wayland protocol server code generated by hyprwayland-scanner (as Hyprland does for its own protocols):
# build/protocols/appmenu.{hpp,cpp} from protocols/appmenu.xml (org_kde_kwin_appmenu, version 2).
# Regenerated when an output is missing, EMPTY or older than the XML: an unclean shutdown can leave zero-size files
# behind, which a timestamp check alone takes for up to date (the next build then failed).
protocols() {
  mkdir -p build/protocols
  local f stale=0
  for f in build/protocols/appmenu.cpp build/protocols/appmenu.hpp; do
    if [[ ! -s $f || protocols/appmenu.xml -nt $f ]]; then
      stale=1
    fi
  done
  if ((stale)); then
    rm -f build/protocols/appmenu.cpp build/protocols/appmenu.hpp
    hyprwayland-scanner protocols/appmenu.xml build/protocols
    for f in build/protocols/appmenu.cpp build/protocols/appmenu.hpp; do
      [[ -s $f ]] || { echo "build-direct: hyprwayland-scanner left $f missing or empty" >&2; exit 1; }
    done
  fi
}

# Lua symbols are resolved at load time from Hyprland's own liblua (5.5): only Lua's headers are needed. The plugin's
# flags are asked of pkg-config only for the modes that build or lint the plugin: the tests need no Hyprland headers
# (a machine or a container without them still runs `tests` and `tests-asan`).
plugin_flags=()
plugin_libs=()
if [[ $what == plugin || $what == all || $what == compdb || $what == tidy ]]; then
  # shellcheck disable=SC2207
  plugin_flags=("-DGRASSFIELD_VERSION=\"$(tr -d "[:space:]" <../VERSION)\"" -std=c++23 -O2 -g -DNDEBUG -fPIC -Wall -Wextra "-I$PWD/build" $(pkg-config --cflags hyprland pixman-1 libdrm glesv2) $(pkg-config --cflags lua))
  # shellcheck disable=SC2207
  plugin_libs=($(pkg-config --libs hyprland pixman-1 libdrm glesv2))
fi
# Pure logic only (src/core): no Hyprland headers, no compositor needed.
# shellcheck disable=SC2207
# GF_PLUGIN_SOURCE_DIR: QuietTest reads the plugin's sources (every key listener opens the quiet scope), as CMakeLists.txt.
# GF_RUN_MODE_VECTORS: RunModeTest reads the run-mode vectors shared with the shell and the apps (ADR-0019).
test_flags=(-std=c++23 -O0 -g -Wall -Wextra "-I$PWD/src" "-DGF_PLUGIN_SOURCE_DIR=\"$PWD/src\"" "-DGF_RUN_MODE_VECTORS=\"$PWD/../tests/fixtures/run-mode-vectors.json\"" $(pkg-config --cflags gtest_main))
# shellcheck disable=SC2207
test_libs=($(pkg-config --libs gtest_main))

if [[ $what == plugin || $what == all ]]; then
  protocols
  # Generated code: its own object, symbols hidden (no clash with a Hyprland that ships the same interface).
  g++ "${plugin_flags[@]}" -fvisibility=hidden -w -c build/protocols/appmenu.cpp -o build/protocols/appmenu.o
  g++ "${plugin_flags[@]}" -shared "${plugin_srcs[@]}" build/protocols/appmenu.o "${plugin_libs[@]}" -o build/grassfield-compositor.so
fi

if [[ $what == tests || $what == all ]]; then
  g++ "${test_flags[@]}" "${test_srcs[@]}" "${core_srcs[@]}" "${test_libs[@]}" -o build/grassfield-compositor-tests
fi

# The same tests under AddressSanitizer and UndefinedBehaviorSanitizer (ADR-0041 step 5: the fuzzed parsers run inside the
# compositor, so a memory error there is a session lost). Not part of `all`: it doubles the build time; scripts/dev/test.sh
# runs the binary when it exists, `just release-check` builds it.
if [[ $what == tests-asan ]]; then
  g++ "${test_flags[@]}" -fsanitize=address,undefined -fno-omit-frame-pointer "${test_srcs[@]}" "${core_srcs[@]}" "${test_libs[@]}" -o build/grassfield-compositor-tests-asan
fi

# One compile command per translation unit, with the exact flags used above. Absolute paths, for the source and the include
# directories: clang-tidy names a header by the path it was found under, and .clang-tidy's HeaderFilterRegex
# ('.*/compositor/(src|tests)/.*') matches only an absolute one (review of c36220a3: with `-c src/...` no finding in our own
# headers was ever reported).
if [[ $what == compdb || $what == all || $what == tidy ]]; then
  protocols
  entry() { # <source> <flags...>   (arguments go through stdin: jq would parse "-std=..." as its own options)
    local src=$1
    shift
    printf '%s\n' g++ "$@" -c "$PWD/$src" | jq -R . | jq -s --arg d "$PWD" --arg f "$PWD/$src" '{directory: $d, file: $f, arguments: .}'
  }
  {
    for src in "${plugin_srcs[@]}"; do entry "$src" "${plugin_flags[@]}"; done
    for src in "${test_srcs[@]}"; do entry "$src" "${test_flags[@]}"; done
  } | jq -s . > build/compile_commands.json
fi

# Gate Q1: clang-tidy over the glue and the core (config: .clang-tidy; analyzer findings are errors).
# Generated protocol code is not linted (its header is outside the HeaderFilterRegex).
if [[ $what == tidy ]]; then
  clang-tidy -p build --quiet "${plugin_srcs[@]}" "${test_srcs[@]}"
fi
